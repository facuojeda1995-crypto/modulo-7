import os
import duckdb
import pandas as pd


def generar_dataset_prueba(ruta_csv):
    """Genera un archivo CSV de ejemplo si no existe en el directorio."""
    if not os.path.exists(ruta_csv):
        df_mock = pd.DataFrame({
            'estacion_id': ['EST_01', 'EST_02', 'EST_01', 'EST_03', 'EST_02'] * 2000,
            'fecha': pd.date_range(start='2023-01-01', periods=10000, freq='h').strftime('%Y-%m-%d'),
            'temperatura': [22.5, 36.1, 15.4, 40.2, 28.0] * 2000,
            'humedad': [60.5, 45.0, 80.2, 30.1, 55.4] * 2000,
            'precipitacion': [0.0, 55.2, 12.0, 0.0, 5.4] * 2000
        })
        df_mock.to_csv(ruta_csv, index=False)


def ejecutar_analisis(ruta_csv):
    """Ejecuta la carga virtual, limpieza y consultas analíticas con DuckDB."""
    con = duckdb.connect(database=':memory:')

    # Etapa 1 y 2: Carga directa desde disco y limpieza de valores nulos
    con.execute(f"""
        CREATE VIEW clima_limpio AS
        SELECT
            estacion_id,
            CAST(fecha AS DATE) AS fecha,
            CAST(temperatura AS FLOAT) AS temperatura,
            CAST(humedad AS FLOAT) AS humedad,
            CAST(precipitacion AS FLOAT) AS precipitacion
        FROM read_csv_auto('{ruta_csv}')
        WHERE temperatura IS NOT NULL;
    """)

    # Consulta 1: Promedios mensuales
    print("--- 1. PROMEDIOS MENSUALES ---")
    print(con.sql("""
        SELECT
            EXTRACT(YEAR FROM fecha) AS anio,
            EXTRACT(MONTH FROM fecha) AS mes,
            ROUND(AVG(temperatura), 2) AS temp_promedio,
            ROUND(AVG(humedad), 2) AS humedad_promedio
        FROM clima_limpio
        GROUP BY anio, mes
        ORDER BY anio DESC, mes DESC;
    """).df())

    # Consulta 2: Máximos históricos por estación
    print("\n--- 2. MÁXIMOS HISTÓRICOS POR ESTACIÓN ---")
    print(con.sql("""
        SELECT
            estacion_id,
            MAX(temperatura) AS temp_maxima,
            MAX(precipitacion) AS lluvia_maxima
        FROM clima_limpio
        GROUP BY estacion_id
        ORDER BY temp_maxima DESC;
    """).df())

    # Consulta 3: Filtrado complejo (eventos climáticos extremos)
    print("\n--- 3. DÍAS EXTREMOS (Temp > 35°C o Lluvia > 50mm) ---")
    print(con.sql("""
        SELECT estacion_id, fecha, temperatura, precipitacion
        FROM clima_limpio
        WHERE temperatura > 35.0 OR precipitacion > 50.0
        LIMIT 5;
    """).df())

    con.close()


if __name__ == '__main__':
    archivo_entrada = "clima_datos.csv"
    generar_dataset_prueba(archivo_entrada)
    ejecutar_analisis(archivo_entrada)